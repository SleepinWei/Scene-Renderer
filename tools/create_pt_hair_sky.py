#!/usr/bin/env python3
"""Freeze the renderer's baked atmosphere into the full Yuksel hair packages.

Keeps source strand control points, widths and materials; regenerates ribbons
for a slightly upward-facing camera so the sky fills the portrait background.
Removes the studio floor and area emitters. The sky supplies both illumination
and the visible background; its finite solar disk is kept separately.
"""
import argparse
import copy
import hashlib
import json
import math
from pathlib import Path
import struct

from create_pt_hair_benchmarks import imported_ribbons, strands
from pt_groom import Package
from pt_hair_file import read_hair


def sha(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024*1024), b''):
            digest.update(block)
    return digest.hexdigest()


def decode_baked_hdr(path, output):
    """Decode stb's -Y/+X, unit-exposure RGBE export to little-endian RGB32F.

    Deliberately accepts only the bake export convention, not arbitrary HDR
    orientations, legacy encodings or exposure corrections.
    """
    with Path(path).open('rb') as source, Path(output).open('wb') as target:
        if source.readline().strip() != b'#?RADIANCE':
            raise ValueError('Expected a Radiance atmosphere bake')
        header = []
        while True:
            line = source.readline()
            if not line or len(header) > 64:
                raise ValueError('Invalid HDR header')
            if not line.strip():
                break
            header.append(line.strip())
        if b'FORMAT=32-bit_rle_rgbe' not in header:
            raise ValueError('Expected RGBE RLE')
        for line in header:
            if line.startswith(b'EXPOSURE=') and float(line.split(b'=')[1]) != 1:
                raise ValueError('Only unit-exposure bake exports are supported')
        dimensions = source.readline().split()
        if len(dimensions) != 4 or dimensions[0] != b'-Y' or dimensions[2] != b'+X':
            raise ValueError('Expected top-first -Y / +X bake orientation')
        height, width = int(dimensions[1]), int(dimensions[3])
        if not 8 <= width <= 8192 or not 1 <= height <= 4096:
            raise ValueError('Invalid environment dimensions')
        minimum, maximum = math.inf, 0
        for _ in range(height):
            if source.read(4) != bytes((2, 2, width >> 8, width & 255)):
                raise ValueError('Invalid or unsupported RGBE scanline')
            channels = []
            for _ in range(4):
                channel = bytearray()
                while len(channel) < width:
                    code = source.read(1)
                    if not code or not code[0]:
                        raise ValueError('Truncated or zero-length RGBE packet')
                    count = code[0]-128 if code[0] > 128 else code[0]
                    block = source.read(1 if code[0] > 128 else count)
                    if len(block) != (1 if code[0] > 128 else count) or len(channel)+count > width:
                        raise ValueError('Invalid RGBE packet extent')
                    channel.extend(block*count if code[0] > 128 else block)
                channels.append(channel)
            pixels = []
            for x in range(width):
                scale = math.ldexp(1., channels[3][x]-136) if channels[3][x] else 0
                pixels.extend(channels[c][x]*scale for c in range(3))
            minimum, maximum = min(minimum, min(pixels)), max(maximum, max(pixels))
            target.write(struct.pack('<'+str(width*3)+'f', *pixels))
        if source.read(1) or maximum <= 0 or minimum == maximum:
            raise ValueError('Bake must contain a nonconstant sky and no trailing data')
    return dict(width=width, height=height, minimum=minimum, maximum=maximum)


def create(source_dir, output, environment, exposure=1):
    source_dir, output, environment = Path(source_dir), Path(output), Path(environment)
    scene = json.loads((source_dir/'scene.json').read_text())
    geometry_path, tangent_path = source_dir/scene['geometry'], source_dir/scene['tangents']
    # These packages are generated by create_pt_hair_benchmarks.py: head, hair,
    # floor, key, fill, rim. Reject a different layout instead of deleting it.
    if len(scene['draws']) != 6 or [scene['draws'][i]['material'] for i in range(2)] != [0, 1]:
        raise ValueError('Expected the Yuksel benchmark studio layout')
    if [m.get('bsdf_model') for m in scene['materials'][:2]] != ['lambert', 'hair']:
        raise ValueError('Expected a Lambert head and hair material')
    if not math.isfinite(exposure) or exposure <= 0:
        raise ValueError('Exposure must be finite and positive')
    hair_path = Path(scene['source']['original_hair'])
    if sha(hair_path) != scene['source']['original_hair_sha256']:
        raise ValueError('Source HAIR differs from the imported benchmark')
    sun = json.loads(Path(str(environment)+'.json').read_text())
    direction, irradiance, radius = sun['sun_direction'], sun['sun_irradiance'], sun['sun_radius']
    if (len(direction) != 3 or len(irradiance) != 3 or
            not all(math.isfinite(v) for v in direction+irradiance+[radius]) or
            abs(sum(v*v for v in direction)-1) > .002 or
            min(irradiance) < 0 or max(irradiance) <= 0 or not 0 < radius <= .1):
        raise ValueError('Invalid solar bake sidecar')
    output.mkdir(parents=True, exist_ok=True)
    if source_dir.resolve() == output.resolve():
        raise ValueError('Sky output must differ from the studio package')
    draws = copy.deepcopy(scene['draws'][:1])
    ranges = {}
    for key, offset_key, stride, magic in [('geometry', 'offset', 32, b'PTMESH01'),
                                            ('tangents', 'tangents_offset', 16, b'PTTANG01')]:
        input_path = source_dir/scene[key]
        with input_path.open('rb') as source, (output/(key+'.bin')).open('wb') as target:
            if source.read(8) != magic:
                raise ValueError('Invalid '+key+' stream')
            target.write(magic)
            ranges[key] = []
            for before, after in zip(scene['draws'][:1], draws):
                source.seek(before[offset_key]); remaining = before['vertices']*stride
                after[offset_key] = target.tell(); digest = hashlib.sha256()
                while remaining:
                    data = source.read(min(remaining, 1024*1024))
                    if not data:
                        raise ValueError('Truncated '+key+' range')
                    target.write(data); digest.update(data); remaining -= len(data)
                ranges[key].append(dict(vertices=before['vertices'], sha256=digest.hexdigest()))
    normalization = scene['source']['normalization']
    scale, center, low = normalization['scale'], normalization['original_center'], normalization['original_low']
    def transform(p):
        return [(p[1]-center[1])*scale,
                (p[2]-low[2])*scale+normalization['floor_offset'],
                (p[0]-center[0])*scale]
    hair = read_hair(hair_path)
    if hair.strands != scene['source']['strands'] or len(hair.points)//3 != scene['source']['points']:
        raise ValueError('Source HAIR counts differ from the imported benchmark')
    package = Package(output, [2.4, -.6, 6.6], [0, 1.42, 0], 29)
    package.geometry = bytearray((output/'geometry.bin').read_bytes())
    package.tangents = bytearray((output/'tangents.bin').read_bytes())
    package.materials = copy.deepcopy(scene['materials'][:2])
    package.draws = draws
    package.store(imported_ribbons(strands(hair, transform, scale), package.eye), 1)
    if package.draws[1]['vertices'] != scene['draws'][1]['vertices']:
        raise ValueError('Regenerated ribbons must retain all source segments')
    # Move the isolated bust and camera together above the nominal ground.
    # Relative coordinates used to regenerate the camera-facing widths stay exact.
    for draw in package.draws:
        draw['model'][13] = 4
    package.eye[1] += 4
    package.target[1] += 4
    source = dict(scene['source'], name=scene['source']['name']+' / atmosphere sky',
                  lighting='Frozen realtime atmosphere + finite solar disk; no studio floor/emitters',
                  reference_camera=package.eye, camera_target=package.target,
                  model_translation=[0, 4, 0])
    package.save(source)
    scene = json.loads((output/'scene.json').read_text())
    sky = decode_baked_hdr(environment, output/'environment.bin')
    scene['geometry'], scene['tangents'] = 'geometry.bin', 'tangents.bin'
    scene.pop('lights', None)
    scene['environment'] = dict(file='environment.bin', width=sky['width'], height=sky['height'])
    scene['sun'] = dict(direction=direction, irradiance=irradiance, radius=radius)
    scene['exposure'] = exposure
    (output/'scene.json').write_text(json.dumps(scene, indent=2)+'\n')
    inputs = [source_dir/'scene.json', geometry_path, tangent_path,
              source_dir/'import.json', hair_path, environment, Path(str(environment)+'.json'), Path(__file__),
              Path(__file__).parent/'create_pt_hair_benchmarks.py', Path(__file__).parent/'pt_hair_file.py',
              Path(__file__).parent/'pt_groom.py']
    (output/'sky-import.json').write_text(json.dumps(dict(
        input_sha256={str(p): sha(p) for p in inputs}, preserved_ranges=ranges,
        camera_unchanged=False, camera_eye=package.eye, camera_target=package.target,
        ribbons_regenerated_for_camera=True, source_points_widths_unchanged=True,
        hair_material_unchanged=True, head_material_unchanged=True,
        removed_draws=4, sky=sky, sun=scene['sun'], exposure=exposure,
        limits='Fixed-eye triangle ribbons; clear atmosphere bake excludes clouds and solar disk'), indent=2)+'\n')
    return output/'scene.json'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=Path('build/pt-hair-benchmarks'))
    parser.add_argument('--output', type=Path, default=Path('build/pt-hair-sky'))
    parser.add_argument('--environment', type=Path, default=Path('build/pt-hair-sky/daylight-environment.hdr'))
    parser.add_argument('--exposure', type=float, default=1)
    args = parser.parse_args()
    for name in ('straight', 'wavy'):
        print(create(args.input/name, args.output/name, args.environment, args.exposure))


if __name__ == '__main__':
    main()
